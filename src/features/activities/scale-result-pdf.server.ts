/**
 * Scale Result PDF — per-activity document (S3).
 *
 * SERVER-ONLY. Two variants:
 *   - "patient"   → Patient sees: score, band, item breakdown, disclaimer
 *   - "therapist" → Clinician sees: + flags, scoring transparency, bands table
 *
 * Brand rules: same as Compliance Report (Navy header, watermark, footer).
 * Zero interpretation. All data derived from instrument responses.
 *
 * Prohibited words: improving, worsening, better, worse, progress,
 *   trend analysis, regression, prediction, RCI, CSI, clinically significant,
 *   HIPAA-certified, court-defensible, legally binding, guaranteed,
 *   diagnosis, treatment plan
 */

import { jsPDF } from "jspdf";
import { supabaseAdmin } from "@/integrations/supabase/client.server";
import { decryptPHIServer } from "@/lib/crypto/encryption.server";
import { logServerError } from "@/lib/logger.server";
import { ICON_PNG_B64, WATERMARK_PNG_B64 } from "./pdf-brand-assets.server";

// ── Brand colors ──
const NAVY = [31, 42, 54] as const;
const CREAM = [244, 239, 230] as const;
const SAGE = [126, 155, 134] as const;
const CHARCOAL = [58, 63, 71] as const;
const WHITE = [255, 255, 255] as const;
const RED = [192, 57, 43] as const;

const M = 18;
const PAGE_W = 210;
const PAGE_H = 297;
const CW = PAGE_W - M * 2;
const FOOTER_ZONE = PAGE_H - 22;

type ScaleResultVariant = "patient" | "therapist";

export interface ScaleResultParams {
  activityResponseId: string;
  workspaceId: string;
  variant: ScaleResultVariant;
  /** Only needed for therapist variant (caller provides) */
  therapistName?: string;
  workspaceName?: string;
  licenseNumber?: string;
  npi?: string;
}

interface ItemBreakdown {
  id: string;
  label: string;
  responseValue: number | null;
  points: number | null;
  weight: number;
  flagLabel: string | null;
}

// ── Shared layout helpers (same as compliance-report) ──

function drawWatermark(doc: jsPDF) {
  const gs = (doc as any).GState;
  if (gs) {
    doc.saveGraphicsState();
    doc.setGState(new gs({ opacity: 0.045 }));
    const size = 120;
    doc.addImage(
      `data:image/png;base64,${WATERMARK_PNG_B64}`,
      "PNG",
      (PAGE_W - size) / 2,
      (PAGE_H - size) / 2,
      size,
      size,
    );
    doc.restoreGraphicsState();
  }
}

function drawHeader(doc: jsPDF): number {
  const barH = 18;
  doc.setFillColor(...NAVY);
  doc.rect(0, 0, PAGE_W, barH, "F");
  const iconSize = 10;
  const iconY = (barH - iconSize) / 2;
  doc.addImage(`data:image/png;base64,${ICON_PNG_B64}`, "PNG", M, iconY, iconSize, iconSize);
  doc.setFont("times", "bold");
  doc.setFontSize(16);
  doc.setTextColor(...CREAM);
  const wmX = M + iconSize + 3;
  const wmY = barH / 2 + 2;
  doc.text("terapily", wmX, wmY);
  const dotX = wmX + doc.getTextWidth("terapily");
  doc.setTextColor(...SAGE);
  doc.text(".", dotX, wmY);
  return barH;
}

function drawFooter(doc: jsPDF, pageNum: number, totalPages: number, variant: ScaleResultVariant) {
  const fy = PAGE_H - 14;
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.3);
  doc.line(M, fy - 2, PAGE_W - M, fy - 2);

  const iconS = 4;
  doc.addImage(`data:image/png;base64,${ICON_PNG_B64}`, "PNG", M, fy - 0.5, iconS, iconS);
  doc.setFont("times", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor(...NAVY);
  const wmX = M + iconS + 1.5;
  doc.text("terapily", wmX, fy + 2);
  doc.setTextColor(...SAGE);
  doc.text(".", wmX + doc.getTextWidth("terapily"), fy + 2);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(6.5);
  doc.setTextColor(...CHARCOAL);
  const yearX = wmX + doc.getTextWidth("terapily.") + 2;
  doc.text(`· ${new Date().getFullYear()}`, yearX, fy + 2);

  doc.setFontSize(7);
  const pg = `${pageNum} / ${totalPages}`;
  const pgW = doc.getTextWidth(pg);
  doc.text(pg, (PAGE_W - pgW) / 2, fy + 2);

  doc.setFontSize(5.5);
  doc.setTextColor(153, 153, 153);
  const disc =
    variant === "patient"
      ? "This document was generated by Terapily. It is not a diagnosis or treatment recommendation."
      : "Platform-generated scoring summary. Does not replace clinical documentation in your EHR.";
  const discW = doc.getTextWidth(disc);
  doc.text(disc, PAGE_W - M - discW, fy + 6);
}

function formatFullDateTime(iso: string): string {
  return new Date(iso).toLocaleString("en-US", {
    month: "short", day: "numeric", year: "numeric",
    hour: "2-digit", minute: "2-digit", timeZoneName: "short",
  });
}

// ── Main builder ──

export async function buildScaleResultPDF(params: ScaleResultParams): Promise<Uint8Array> {
  const { activityResponseId, workspaceId, variant } = params;

  // 1. Fetch activity_response
  const { data: resp, error: respErr } = await supabaseAdmin
    .from("activity_responses")
    .select("*")
    .eq("id", activityResponseId)
    .eq("workspace_id", workspaceId)
    .single();

  if (respErr || !resp) {
    throw new Error("Activity response not found.");
  }

  // 2. Fetch patient
  const { data: patient } = await supabaseAdmin
    .from("patients")
    .select("display_name, full_name_encrypted")
    .eq("id", resp.patient_id)
    .eq("workspace_id", workspaceId)
    .maybeSingle();

  let patientLabel = patient?.display_name ?? "Participant";
  let hasPHI = false;
  if (patient?.full_name_encrypted) {
    try {
      const decrypted = await decryptPHIServer(patient.full_name_encrypted);
      if (decrypted) { patientLabel = decrypted; hasPHI = true; }
    } catch (err) { logServerError("scale-result-pdf.decrypt", err); }
  }

  // 3. Fetch activity catalog
  const { data: activity } = await supabaseAdmin
    .from("activity_catalog")
    .select("title, slug, config, archetype")
    .eq("id", resp.activity_id)
    .single();

  if (!activity) throw new Error("Activity not found in catalog.");

  const config = (activity.config ?? {}) as {
    scoring?: {
      type?: string;
      questions?: Array<{ id: string; label?: string; weight?: number }>;
      reverse?: string[];
      max_per_item?: number;
      clusters?: Record<string, string[]>;
    };
    severity_bands?: Array<{ min: number; max: number; label: string }>;
    items?: Array<{ id: string; text?: string; label?: string; clinical_flag?: string; flag_threshold?: number }>;
    introduction?: string;
  };

  // 4. Decrypt raw responses for item breakdown
  let rawResponses: Record<string, number> = {};
  if (resp.raw_responses_encrypted) {
    try {
      const decrypted = await decryptPHIServer(resp.raw_responses_encrypted);
      if (decrypted) rawResponses = JSON.parse(decrypted);
    } catch (err) { logServerError("scale-result-pdf.decrypt-responses", err); }
  }

  // 5. Build item breakdown
  const questions = config.scoring?.questions ?? [];
  const itemsConfig = config.items ?? [];
  const reverseSet = new Set(config.scoring?.reverse ?? []);
  const maxPerItem = typeof config.scoring?.max_per_item === "number" ? config.scoring.max_per_item : null;
  const scoringType = config.scoring?.type ?? "sum";

  const maxPossibleScore = questions.reduce((acc, q) => {
    const w = scoringType === "weighted_sum" ? (q.weight ?? 1) : 1;
    return acc + (maxPerItem ?? 3) * w;
  }, 0);

  const items: ItemBreakdown[] = questions.map((q) => {
    const itemConf = itemsConfig.find((ic) => ic.id === q.id);
    const rawVal = typeof rawResponses[q.id] === "number" ? rawResponses[q.id] : null;
    let points: number | null = null;
    if (rawVal !== null) {
      let val = rawVal;
      if (reverseSet.has(q.id) && maxPerItem !== null) val = maxPerItem - val;
      const weight = scoringType === "weighted_sum" ? (q.weight ?? 1) : 1;
      points = val * weight;
    }
    let flagLabel: string | null = null;
    if (variant === "therapist" && itemConf?.clinical_flag && rawVal !== null) {
      const threshold = typeof itemConf.flag_threshold === "number" ? itemConf.flag_threshold : 1;
      if (rawVal >= threshold) flagLabel = itemConf.clinical_flag;
    }
    return {
      id: q.id,
      label: q.label ?? itemConf?.text ?? itemConf?.label ?? q.id,
      responseValue: rawVal,
      points,
      weight: scoringType === "weighted_sum" ? (q.weight ?? 1) : 1,
      flagLabel,
    };
  });

  // 6. Fetch delivery_mode from patient_activities
  const { data: pa } = await supabaseAdmin
    .from("patient_activities")
    .select("delivery_mode")
    .eq("id", resp.patient_activity_id)
    .maybeSingle();

  const deliveryMode = pa?.delivery_mode ?? resp.submitted_via ?? "unknown";

  // 7. Build PDF
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  let totalPages = 1;
  let currentPage = 1;

  function checkPage(y: number, needed = 10): number {
    if (y + needed > FOOTER_ZONE) {
      drawFooter(doc, currentPage, totalPages, variant);
      doc.addPage();
      currentPage++;
      drawWatermark(doc);
      return drawHeader(doc) + 9;
    }
    return y;
  }

  drawWatermark(doc);
  let y = drawHeader(doc);

  // Clinician copy band (therapist only)
  if (variant === "therapist") {
    const bandH = 10;
    doc.setFillColor(253, 232, 232);
    doc.rect(0, y, PAGE_W, bandH, "F");
    doc.setTextColor(...RED);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    const bandLabel = "CLINICIAN COPY — NOT INTENDED FOR PATIENT DISTRIBUTION";
    const bandW = doc.getTextWidth(bandLabel);
    doc.text(bandLabel, (PAGE_W - bandW) / 2, y + bandH / 2 + 1.5);
    y += bandH;
  }

  y += 10;

  // Title
  doc.setTextColor(...NAVY);
  doc.setFont("times", "bold");
  doc.setFontSize(20);
  doc.text(variant === "patient" ? "Activity Result" : "Clinical Activity Result", M, y);
  y += 5;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...CHARCOAL);
  doc.text(
    variant === "patient"
      ? "Summary of your responses"
      : "Detailed scoring for your clinical records",
    M, y,
  );
  y += 5;

  // PHI warning (therapist only)
  if (variant === "therapist" && hasPHI) {
    y += 2;
    doc.setFillColor(255, 243, 224);
    doc.roundedRect(M, y, CW, 8, 1.5, 1.5, "F");
    doc.setTextColor(230, 81, 0);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(7);
    doc.text("PHI WARNING:", M + 3, y + 5);
    doc.setFont("helvetica", "normal");
    doc.text("This document contains Protected Health Information. Store securely per your practice's policies.", M + 28, y + 5);
    y += 10;
  } else {
    y += 3;
  }

  // Info box
  const genStr = formatFullDateTime(new Date().toISOString());
  const infoItems: [string, string][] = [
    [variant === "patient" ? "Participant:" : "Patient:", patientLabel],
    ["Activity:", activity.title],
    ["Date:", formatFullDateTime(resp.submitted_at)],
    ["Mode:", deliveryMode.replace("_", " ")],
  ];
  if (variant === "therapist") {
    if (params.therapistName) infoItems.push(["Therapist:", params.therapistName]);
    if (params.workspaceName) infoItems.push(["Practice:", params.workspaceName]);
    if (params.licenseNumber) infoItems.push(["License:", params.licenseNumber]);
    if (params.npi) infoItems.push(["NPI:", params.npi]);
    infoItems.push(["Generated:", genStr]);
  } else {
    infoItems.push(["Generated:", genStr]);
  }

  const infoLineH = 6;
  const infoPadY = 6;
  const infoBoxH = infoPadY * 2 + infoItems.length * infoLineH;
  doc.setFillColor(247, 245, 240);
  doc.roundedRect(M, y, CW, infoBoxH, 2, 2, "F");
  let iy = y + infoPadY + 4;
  for (const [label, val] of infoItems) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...NAVY);
    doc.text(label, M + 4, iy);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...CHARCOAL);
    doc.text(val, M + 30, iy);
    iy += infoLineH;
  }
  y += infoBoxH + 8;

  // Score result box
  y = checkPage(y, 28);
  doc.setDrawColor(...SAGE);
  doc.setLineWidth(0.6);
  doc.setFillColor(247, 250, 248);
  doc.roundedRect(M, y, CW, variant === "therapist" ? 30 : 22, 2, 2, "FD");
  let ry = y + 7;
  doc.setTextColor(...NAVY);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(variant === "patient" ? "Your Score:" : "Total Score:", M + 4, ry);
  doc.setFont("times", "bold");
  doc.setFontSize(18);
  const scoreStr = resp.score != null ? `${resp.score}` : "—";
  const maxStr = maxPossibleScore > 0 ? ` / ${maxPossibleScore}` : "";
  doc.text(`${scoreStr}${maxStr}`, M + 40, ry);
  ry += 8;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...CHARCOAL);
  const bandLabel = resp.severity && resp.severity !== "not_applicable"
    ? `Band (per instrument definition): ${resp.severity}`
    : "Band: N/A";
  doc.text(bandLabel, M + 4, ry);

  if (variant === "therapist") {
    ry += 6;
    const meta = (resp.scoring_metadata ?? {}) as Record<string, unknown>;
    const answered = meta.answered ?? questions.length;
    const expected = meta.expected ?? questions.length;
    const completion = meta.completion_rate ?? 1;
    doc.text(`Items answered: ${answered} / ${expected} · Completion: ${Math.round(Number(completion) * 100)}%`, M + 4, ry);
  }

  y += (variant === "therapist" ? 30 : 22) + 8;

  // Cluster subscores (therapist only, e.g. PCL-5)
  if (variant === "therapist") {
    const meta = (resp.scoring_metadata ?? {}) as Record<string, unknown>;
    const clusters = meta.clusters as Record<string, number> | undefined;
    if (clusters && Object.keys(clusters).length > 0) {
      y = checkPage(y, 20);
      doc.setTextColor(...NAVY);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      doc.text("Cluster Subscores", M, y);
      y += 6;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(...CHARCOAL);
      for (const [name, score] of Object.entries(clusters)) {
        doc.text(`${name}: ${score}`, M + 4, y);
        y += 5;
      }
      y += 4;
    }
  }

  // Item-by-item breakdown table
  y = checkPage(y, 30);
  doc.setTextColor(...NAVY);
  doc.setFont("times", "bold");
  doc.setFontSize(12);
  doc.text(variant === "patient" ? "Your Responses" : "Item-by-Item Breakdown", M, y);
  y += 7;

  if (items.length > 0) {
    const hasFlags = variant === "therapist" && items.some((it) => it.flagLabel);
    const colX = hasFlags
      ? [M + 2, M + 10, M + 100, M + 130, M + 150]
      : [M + 2, M + 10, M + 110, M + 140];
    const headers = hasFlags
      ? ["#", "Item", "Response", "Points", "Flag"]
      : ["#", "Item", "Response", "Points"];

    const thH = 8;
    function drawTableHeader(atY: number): number {
      doc.setFillColor(...NAVY);
      doc.roundedRect(M, atY, CW, thH, 1, 1, "F");
      doc.setTextColor(...WHITE);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(7);
      const thY = atY + thH / 2 + 1.5;
      for (let h = 0; h < headers.length; h++) {
        doc.text(headers[h], colX[h], thY);
      }
      return atY + thH + 1;
    }

    y = drawTableHeader(y);

    const ROW_H = 8;
    for (let i = 0; i < items.length; i++) {
      if (y + ROW_H > FOOTER_ZONE) {
        drawFooter(doc, currentPage, totalPages, variant);
        doc.addPage();
        currentPage++;
        drawWatermark(doc);
        y = drawHeader(doc) + 9;
        y = drawTableHeader(y);
      }
      if (i % 2 === 0) {
        doc.setFillColor(249, 247, 243);
        doc.rect(M, y, CW, ROW_H, "F");
      }
      const item = items[i];
      const textY = y + ROW_H / 2 + 1;
      doc.setTextColor(...CHARCOAL);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7);
      doc.text(`${i + 1}`, colX[0], textY);
      const labelTrunc = item.label.length > 55 ? item.label.slice(0, 52) + "…" : item.label;
      doc.text(labelTrunc, colX[1], textY);
      doc.text(item.responseValue != null ? `${item.responseValue}` : "—", colX[2], textY);
      doc.setFont("helvetica", "bold");
      doc.text(item.points != null ? `${item.points}` : "—", colX[3], textY);
      if (hasFlags && item.flagLabel) {
        doc.setTextColor(...RED);
        doc.setFontSize(6.5);
        doc.text(`⚠ ${item.flagLabel}`, colX[4], textY);
      }
      y += ROW_H;
    }

    // Total row
    y = checkPage(y, ROW_H + 2);
    doc.setFillColor(...SAGE);
    doc.roundedRect(M, y, CW, ROW_H, 1, 1, "F");
    doc.setTextColor(...WHITE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    const totalTextY = y + ROW_H / 2 + 1.5;
    doc.text("TOTAL", colX[1], totalTextY);
    doc.text(resp.score != null ? `${resp.score}${maxStr}` : "—", colX[3], totalTextY);
    y += ROW_H + 6;
  }

  // Scoring transparency (therapist only)
  if (variant === "therapist") {
    y = checkPage(y, 30);
    doc.setTextColor(...NAVY);
    doc.setFont("times", "bold");
    doc.setFontSize(12);
    doc.text("Scoring Transparency", M, y);
    y += 7;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...CHARCOAL);

    doc.text(`Scoring method: ${scoringType === "weighted_sum" ? "Weighted Sum" : "Sum"}`, M, y);
    y += 5;
    doc.text(`Instrument: ${activity.title}`, M, y);
    y += 5;

    const bands = config.severity_bands ?? [];
    if (bands.length > 0) {
      doc.text("Defined bands:", M, y);
      y += 5;
      for (const band of bands) {
        y = checkPage(y, 5);
        doc.text(`  ${band.min}–${band.max}: ${band.label}`, M + 4, y);
        y += 4;
      }
      y += 3;
    }
  }

  // Clinical flags summary (therapist only)
  if (variant === "therapist") {
    const flaggedItems = items.filter((it) => it.flagLabel);
    if (flaggedItems.length > 0) {
      y = checkPage(y, 20);
      doc.setTextColor(...NAVY);
      doc.setFont("times", "bold");
      doc.setFontSize(12);
      doc.text("Clinical Flags", M, y);
      y += 7;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(...CHARCOAL);

      for (const fi of flaggedItems) {
        y = checkPage(y, 12);
        doc.setFillColor(255, 243, 224);
        doc.roundedRect(M, y, CW, 10, 1.5, 1.5, "F");
        doc.setTextColor(230, 81, 0);
        doc.setFont("helvetica", "bold");
        doc.setFontSize(7.5);
        doc.text(`⚠ ${fi.flagLabel}`, M + 3, y + 4);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(7);
        doc.setTextColor(...CHARCOAL);
        doc.text(`Item: ${fi.label} · Response value: ${fi.responseValue}`, M + 3, y + 8);
        y += 12;
      }
      y += 4;
    }
  }

  // Important Notice (patient) or Notices (therapist)
  y = checkPage(y, 35);
  if (variant === "patient") {
    const noticeH = 34;
    doc.setFillColor(255, 248, 225);
    doc.roundedRect(M, y, CW, noticeH, 2, 2, "F");
    doc.setDrawColor(240, 208, 96);
    doc.setLineWidth(0.4);
    doc.roundedRect(M, y, CW, noticeH, 2, 2, "S");
    let ny = y + 5;
    doc.setTextColor(...NAVY);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text("Important Notice", M + 4, ny);
    ny += 5;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...CHARCOAL);
    const lines = [
      `The score presented above reflects your responses to a validated clinical instrument`,
      `(${activity.title}) and is provided for informational purposes only. It does not`,
      `constitute a diagnosis, clinical assessment, or treatment recommendation.`,
      ``,
      `Please discuss these results with your therapist or a qualified mental health professional.`,
      ``,
      `This document does not replace a clinical evaluation.`,
    ];
    for (const line of lines) { doc.text(line, M + 4, ny); ny += 4; }
  } else {
    doc.setTextColor(...NAVY);
    doc.setFont("times", "bold");
    doc.setFontSize(12);
    doc.text("Notices", M, y);
    y += 7;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...CHARCOAL);
    const notices = [
      `This document is a platform-generated scoring summary for ${activity.title}. ` +
      `Scores are computed using the instrument's published scoring algorithm. ` +
      `Item-level data is provided for transparency. ` +
      `Clinical interpretation remains the sole responsibility of the treating clinician.`,
      ``,
      `Follow applicable legal and professional guidelines.`,
    ];
    for (const notice of notices) {
      const wrapped = doc.splitTextToSize(notice, CW - 2);
      for (const line of wrapped) {
        y = checkPage(y, 5);
        doc.setTextColor(...CHARCOAL);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(7.5);
        doc.text(line, M, y);
        y += 4;
      }
    }
  }

  // Footer on last page
  drawFooter(doc, currentPage, totalPages, variant);

  // Fix page count
  totalPages = currentPage;
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let p = 1; p <= pageCount; p++) {
    doc.setPage(p);
    doc.setFillColor(255, 255, 255);
    doc.rect(PAGE_W / 2 - 15, PAGE_H - 16, 30, 6, "F");
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...CHARCOAL);
    const pg = `${p} / ${totalPages}`;
    const pgW = doc.getTextWidth(pg);
    doc.text(pg, (PAGE_W - pgW) / 2, PAGE_H - 12);
  }

  return doc.output("arraybuffer") as unknown as Uint8Array;
}
