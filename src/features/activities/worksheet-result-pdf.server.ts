/**
 * Worksheet Result PDF — per-activity document for structured_form archetype.
 *
 * SERVER-ONLY. Two variants:
 *   - "patient"   → Patient sees: all written responses, step-by-step
 *   - "therapist" → Clinician sees: + PHI, flags, professional header
 *
 * KEY DIFFERENCE from Scale Result PDF:
 *   Worksheets display the FULL TEXT of each written response —
 *   this is the core purpose (making thoughts visible on paper).
 *   Scales show numeric scores; worksheets show narrative content.
 *
 * Brand rules: same as Scale Result (Navy header, watermark, footer).
 */

import { jsPDF } from "jspdf";
import { supabaseAdmin } from "@/integrations/supabase/client.server";
import { decryptPHIServer } from "@/lib/crypto/encryption.server";
import { logServerError } from "@/lib/logger.server";
import { ICON_PNG_B64, WATERMARK_PNG_B64 } from "./pdf-brand-assets.server";

// ── Brand colors ──
const NAVY = [31, 42, 54] as const;
const CREAM = [244, 239, 230] as const;
const SAGE = [126, 155, 134] as const;
const CHARCOAL = [58, 63, 71] as const;
const WHITE = [255, 255, 255] as const;
const RED = [192, 57, 43] as const;

const M = 18;
const PAGE_W = 210;
const PAGE_H = 297;
const CW = PAGE_W - M * 2;
const FOOTER_ZONE = PAGE_H - 22;

type WorksheetResultVariant = "patient" | "therapist";

export interface WorksheetResultParams {
  activityResponseId: string;
  workspaceId: string;
  variant: WorksheetResultVariant;
  therapistName?: string;
  workspaceName?: string;
  licenseNumber?: string;
  npi?: string;
}

interface FormField {
  id: string;
  type: string;
  label: string;
  options?: Array<{ value: string; label: string }>;
  emotions?: string[];
}

interface FormStep {
  id: string;
  title: string;
  description?: string;
  fields: FormField[];
}

// ── Shared layout helpers ──

function drawWatermark(doc: jsPDF) {
  const gs = (doc as any).GState;
  if (gs) {
    doc.saveGraphicsState();
    doc.setGState(new gs({ opacity: 0.045 }));
    const size = 120;
    doc.addImage(
      `data:image/png;base64,${WATERMARK_PNG_B64}`,
      "PNG",
      (PAGE_W - size) / 2,
      (PAGE_H - size) / 2,
      size,
      size,
    );
    doc.restoreGraphicsState();
  }
}

function drawHeader(doc: jsPDF): number {
  const barH = 18;
  doc.setFillColor(...NAVY);
  doc.rect(0, 0, PAGE_W, barH, "F");
  const iconSize = 10;
  const iconY = (barH - iconSize) / 2;
  doc.addImage(`data:image/png;base64,${ICON_PNG_B64}`, "PNG", M, iconY, iconSize, iconSize);
  doc.setFont("times", "bold");
  doc.setFontSize(16);
  doc.setTextColor(...CREAM);
  const wmX = M + iconSize + 3;
  const wmY = barH / 2 + 2;
  doc.text("terapily", wmX, wmY);
  const dotX = wmX + doc.getTextWidth("terapily");
  doc.setTextColor(...SAGE);
  doc.text(".", dotX, wmY);
  return barH;
}

function drawFooter(doc: jsPDF, pageNum: number, totalPages: number, variant: WorksheetResultVariant) {
  const fy = PAGE_H - 14;
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.3);
  doc.line(M, fy - 2, PAGE_W - M, fy - 2);

  const iconS = 4;
  doc.addImage(`data:image/png;base64,${ICON_PNG_B64}`, "PNG", M, fy - 0.5, iconS, iconS);
  doc.setFont("times", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor(...NAVY);
  const wmX = M + iconS + 1.5;
  doc.text("terapily", wmX, fy + 2);
  doc.setTextColor(...SAGE);
  doc.text(".", wmX + doc.getTextWidth("terapily"), fy + 2);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(6.5);
  doc.setTextColor(...CHARCOAL);
  const yearX = wmX + doc.getTextWidth("terapily.") + 2;
  doc.text(`· ${new Date().getFullYear()}`, yearX, fy + 2);

  doc.setFontSize(7);
  const pg = `${pageNum} / ${totalPages}`;
  const pgW = doc.getTextWidth(pg);
  doc.text(pg, (PAGE_W - pgW) / 2, fy + 2);

  doc.setFontSize(5.5);
  doc.setTextColor(153, 153, 153);
  const disc =
    variant === "patient"
      ? "This document was generated by Terapily. It contains your personal responses."
      : "Platform-generated worksheet summary. Contains PHI. Store securely per your practice's policies.";
  const discW = doc.getTextWidth(disc);
  doc.text(disc, PAGE_W - M - discW, fy + 6);
}

function formatFullDateTime(iso: string): string {
  return new Date(iso).toLocaleString("en-US", {
    month: "short", day: "numeric", year: "numeric",
    hour: "2-digit", minute: "2-digit", timeZoneName: "short",
  });
}

function formatResponseValue(
  value: unknown,
  field: FormField,
): string {
  if (value === null || value === undefined || value === "") return "—";

  // emotion_picker: { emotion: string, intensity: number }[] or object
  if (field.type === "emotion_picker") {
    const arr = Array.isArray(value)
      ? value
      : (typeof value === "object" && Array.isArray((value as any)?.emotions))
        ? (value as any).emotions
        : null;
    if (arr) {
      return arr
        .map((e: any) => `${e.name ?? e.emotion ?? e.label ?? "?"} (${e.intensity ?? e.value ?? "?"}%)`)
        .join(", ");
    }
    return "—";
  }

  // multi_select: array of values
  if (field.type === "multi_select" && Array.isArray(value)) {
    const labels = value.map((v) => {
      const opt = field.options?.find((o) => o.value === String(v));
      return opt?.label ?? String(v);
    });
    return labels.join(", ");
  }

  // select / radio: resolve label
  if ((field.type === "select" || field.type === "radio") && field.options) {
    const opt = field.options.find((o) => o.value === String(value));
    if (opt) return opt.label;
  }

  // checkbox
  if (field.type === "checkbox") {
    return value === true || value === "true" ? "Yes" : "No";
  }

  // slider / number
  if (field.type === "slider" || field.type === "number") {
    return String(value);
  }

  return String(value);
}

// ── Main builder ──

export async function buildWorksheetResultPDF(params: WorksheetResultParams): Promise<Uint8Array> {
  const { activityResponseId, workspaceId, variant } = params;

  // 1. Fetch activity_response
  const { data: resp, error: respErr } = await supabaseAdmin
    .from("activity_responses")
    .select("*")
    .eq("id", activityResponseId)
    .eq("workspace_id", workspaceId)
    .single();

  if (respErr || !resp) {
    throw new Error("Activity response not found.");
  }

  // 2. Fetch patient
  const { data: patient } = await supabaseAdmin
    .from("patients")
    .select("display_name, full_name_encrypted")
    .eq("id", resp.patient_id)
    .eq("workspace_id", workspaceId)
    .maybeSingle();

  let patientLabel = patient?.display_name ?? "Participant";
  let hasPHI = false;
  if (patient?.full_name_encrypted) {
    try {
      const decrypted = await decryptPHIServer(patient.full_name_encrypted);
      if (decrypted) { patientLabel = decrypted; hasPHI = true; }
    } catch (err) { logServerError("worksheet-result-pdf.decrypt", err); }
  }

  // 3. Fetch activity catalog
  const { data: activity } = await supabaseAdmin
    .from("activity_catalog")
    .select("title, slug, config, archetype")
    .eq("id", resp.activity_id)
    .single();

  if (!activity) throw new Error("Activity not found in catalog.");

  const config = (activity.config ?? {}) as {
    steps?: FormStep[];
    introduction?: string;
  };

  const steps = config.steps ?? [];

  // 4. Decrypt raw responses
  let rawResponses: Record<string, unknown> = {};
  if (resp.raw_responses_encrypted) {
    try {
      const decrypted = await decryptPHIServer(resp.raw_responses_encrypted);
      if (decrypted) rawResponses = JSON.parse(decrypted);
    } catch (err) { logServerError("worksheet-result-pdf.decrypt-responses", err); }
  }

  // 5. Fetch delivery_mode
  const { data: pa } = await supabaseAdmin
    .from("patient_activities")
    .select("delivery_mode")
    .eq("id", resp.patient_activity_id)
    .maybeSingle();

  const deliveryMode = pa?.delivery_mode ?? resp.submitted_via ?? "unknown";

  // 6. Build PDF
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  let totalPages = 1;
  let currentPage = 1;

  function checkPage(y: number, needed = 10): number {
    if (y + needed > FOOTER_ZONE) {
      drawFooter(doc, currentPage, totalPages, variant);
      doc.addPage();
      currentPage++;
      drawWatermark(doc);
      return drawHeader(doc) + 9;
    }
    return y;
  }

  drawWatermark(doc);
  let y = drawHeader(doc);

  // Clinician copy band (therapist only)
  if (variant === "therapist") {
    const bandH = 10;
    doc.setFillColor(253, 232, 232);
    doc.rect(0, y, PAGE_W, bandH, "F");
    doc.setTextColor(...RED);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    const bandLabel = "CLINICIAN COPY — NOT INTENDED FOR PATIENT DISTRIBUTION";
    const bandW = doc.getTextWidth(bandLabel);
    doc.text(bandLabel, (PAGE_W - bandW) / 2, y + bandH / 2 + 1.5);
    y += bandH;
  }

  y += 10;

  // Title
  doc.setTextColor(...NAVY);
  doc.setFont("times", "bold");
  doc.setFontSize(20);
  doc.text(variant === "patient" ? "Worksheet Responses" : "Worksheet Clinical Record", M, y);
  y += 5;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...CHARCOAL);
  doc.text(
    variant === "patient"
      ? "Your complete responses to this activity"
      : "Full patient responses for your clinical records",
    M, y,
  );
  y += 5;

  // PHI warning (therapist only)
  if (variant === "therapist" && hasPHI) {
    y += 2;
    doc.setFillColor(255, 243, 224);
    doc.roundedRect(M, y, CW, 8, 1.5, 1.5, "F");
    doc.setTextColor(230, 81, 0);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(7);
    doc.text("PHI WARNING:", M + 3, y + 5);
    doc.setFont("helvetica", "normal");
    doc.text("This document contains Protected Health Information. Store securely per your practice's policies.", M + 28, y + 5);
    y += 10;
  } else {
    y += 3;
  }

  // Info box
  const genStr = formatFullDateTime(new Date().toISOString());
  const infoItems: [string, string][] = [
    [variant === "patient" ? "Participant:" : "Patient:", patientLabel],
    ["Activity:", activity.title],
    ["Date:", formatFullDateTime(resp.submitted_at)],
    ["Mode:", deliveryMode.replace("_", " ")],
  ];
  if (variant === "therapist") {
    if (params.therapistName) infoItems.push(["Therapist:", params.therapistName]);
    if (params.workspaceName) infoItems.push(["Practice:", params.workspaceName]);
    if (params.licenseNumber) infoItems.push(["License:", params.licenseNumber]);
    if (params.npi) infoItems.push(["NPI:", params.npi]);
    infoItems.push(["Generated:", genStr]);
  } else {
    infoItems.push(["Generated:", genStr]);
  }

  const infoLineH = 6;
  const infoPadY = 6;
  const infoBoxH = infoPadY * 2 + infoItems.length * infoLineH;
  doc.setFillColor(247, 245, 240);
  doc.roundedRect(M, y, CW, infoBoxH, 2, 2, "F");
  let iy = y + infoPadY + 4;
  for (const [label, val] of infoItems) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...NAVY);
    doc.text(label, M + 4, iy);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...CHARCOAL);
    doc.text(val, M + 30, iy);
    iy += infoLineH;
  }
  y += infoBoxH + 8;

  // ── RESPONSES: Step-by-step ──
  for (let si = 0; si < steps.length; si++) {
    const step = steps[si];

    // Step header
    y = checkPage(y, 20);
    doc.setFillColor(...SAGE);
    doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
    doc.setTextColor(...WHITE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text(`Step ${si + 1}: ${step.title}`, M + 4, y + 6);
    y += 13;

    if (step.description) {
      doc.setFont("helvetica", "italic");
      doc.setFontSize(7.5);
      doc.setTextColor(...CHARCOAL);
      const descLines = doc.splitTextToSize(step.description, CW - 8);
      for (const dl of descLines) {
        y = checkPage(y, 4);
        doc.text(dl, M + 4, y);
        y += 4;
      }
      y += 3;
    }

    // Fields within the step
    for (const field of step.fields) {
      const responseValue = rawResponses[field.id];

      // Field label
      y = checkPage(y, 18);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);
      doc.setTextColor(...NAVY);
      doc.text(field.label, M + 2, y);
      y += 5;

      // ── emotion_picker: visual emotion bars ──
      // Data shape from FormRunner: { emotions: [{ name, intensity }] } OR flat array
      const isEmotionPicker = field.type === "emotion_picker";
      const emotionList = isEmotionPicker && responseValue != null && typeof responseValue === "object"
        ? (Array.isArray(responseValue)
            ? responseValue
            : Array.isArray((responseValue as any).emotions)
              ? (responseValue as any).emotions
              : []) as Array<{ name?: string; emotion?: string; label?: string; intensity?: number; value?: number }>
        : [];

      if (isEmotionPicker && emotionList.length > 0) {
        const emotionH = emotionList.length * 10 + 8;
        y = checkPage(y, emotionH + 2);

        doc.setFillColor(252, 251, 248);
        doc.setDrawColor(220, 218, 210);
        doc.setLineWidth(0.3);
        doc.roundedRect(M + 2, y, CW - 4, emotionH, 1.5, 1.5, "FD");

        let ey = y + 5;
        const barX = M + 40;
        const barW = CW - 48;
        for (const emo of emotionList) {
          const name = emo.name ?? emo.emotion ?? emo.label ?? "—";
          const intensity = emo.intensity ?? emo.value ?? 0;
          const pct = Math.max(0, Math.min(100, Number(intensity)));

          // Emotion name
          doc.setFont("helvetica", "normal");
          doc.setFontSize(8);
          doc.setTextColor(...CHARCOAL);
          doc.text(name, M + 6, ey + 1);

          // Background bar (light gray)
          const barH = 4;
          doc.setFillColor(230, 228, 222);
          doc.roundedRect(barX, ey - 2.5, barW, barH, 1, 1, "F");

          // Filled bar (Sage)
          if (pct > 0) {
            const fillW = Math.max(2, (pct / 100) * barW);
            doc.setFillColor(...SAGE);
            doc.roundedRect(barX, ey - 2.5, fillW, barH, 1, 1, "F");
          }

          // Percentage label
          doc.setFont("helvetica", "bold");
          doc.setFontSize(7);
          doc.setTextColor(...NAVY);
          const pctLabel = `${pct}%`;
          doc.text(pctLabel, barX + barW + 2, ey + 0.5);

          ey += 10;
        }

        y += emotionH + 4;

      // ── slider / number: visual bar ──
      } else if ((field.type === "slider" || field.type === "number") && responseValue != null) {
        const num = Number(responseValue);
        const min = (field as any).min ?? 0;
        const max = (field as any).max ?? 100;
        const pct = max > min ? ((num - min) / (max - min)) * 100 : 0;

        const barBoxH = 16;
        y = checkPage(y, barBoxH + 2);

        doc.setFillColor(252, 251, 248);
        doc.setDrawColor(220, 218, 210);
        doc.setLineWidth(0.3);
        doc.roundedRect(M + 2, y, CW - 4, barBoxH, 1.5, 1.5, "FD");

        const barX = M + 6;
        const barW = CW - 30;
        const barY = y + barBoxH / 2 - 2;
        const barH = 4;

        // Background
        doc.setFillColor(230, 228, 222);
        doc.roundedRect(barX, barY, barW, barH, 1, 1, "F");
        // Fill
        if (pct > 0) {
          const fillW = Math.max(2, (pct / 100) * barW);
          doc.setFillColor(...SAGE);
          doc.roundedRect(barX, barY, fillW, barH, 1, 1, "F");
        }
        // Value label
        doc.setFont("helvetica", "bold");
        doc.setFontSize(9);
        doc.setTextColor(...NAVY);
        doc.text(String(num), barX + barW + 3, barY + 3.5);

        // Min/max labels
        const minLabel = (field as any).minLabel ?? String(min);
        const maxLabel = (field as any).maxLabel ?? String(max);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(6);
        doc.setTextColor(153, 153, 153);
        doc.text(minLabel, barX, barY + barH + 4);
        const maxLabelW = doc.getTextWidth(maxLabel);
        doc.text(maxLabel, barX + barW - maxLabelW, barY + barH + 4);

        y += barBoxH + 4;

      // ── Default: text box ──
      } else {
        const formatted = formatResponseValue(responseValue, field);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(8);
        doc.setTextColor(...CHARCOAL);

        const wrappedLines = doc.splitTextToSize(formatted, CW - 12);
        const boxH = Math.max(8, wrappedLines.length * 4.5 + 6);

        y = checkPage(y, boxH + 2);
        doc.setFillColor(252, 251, 248);
        doc.setDrawColor(220, 218, 210);
        doc.setLineWidth(0.3);
        doc.roundedRect(M + 2, y, CW - 4, boxH, 1.5, 1.5, "FD");

        let ty = y + 4.5;
        for (const line of wrappedLines) {
          doc.text(line, M + 6, ty);
          ty += 4.5;
        }

        y += boxH + 4;
      }

      // Clinical flag indicator (therapist only)
      if (variant === "therapist" && (field as any).clinical_flag) {
        const flagText = (field as any).clinical_flag as string;
        y = checkPage(y, 8);
        doc.setFillColor(255, 243, 224);
        doc.roundedRect(M + 2, y, CW - 4, 7, 1, 1, "F");
        doc.setTextColor(230, 81, 0);
        doc.setFont("helvetica", "bold");
        doc.setFontSize(6.5);
        doc.text(`⚠ Clinical flag: ${flagText}`, M + 5, y + 4.5);
        y += 9;
      }
    }

    y += 4;
  }

  // ── Data sharing notice ──
  y = checkPage(y, 35);
  const padX = 6;
  const padTop = 7;
  const padBottom = 7;
  const titleLineH = 6;
  const bodyLineH = 4;

  if (variant === "patient") {
    const bodyLines = [
      `This document contains your personal responses to "${activity.title}".`,
      `These responses were recorded with your consent and are provided for your`,
      `personal reference. This is not a clinical assessment or diagnosis.`,
      ``,
      `Your therapist may also have access to these responses as part of your`,
      `treatment. If you have questions, please discuss with your therapist.`,
      ``,
      `This document does not replace a clinical evaluation.`,
    ];
    const noticeH = padTop + titleLineH + bodyLines.length * bodyLineH + padBottom;
    doc.setFillColor(255, 248, 225);
    doc.roundedRect(M, y, CW, noticeH, 2, 2, "F");
    doc.setDrawColor(240, 208, 96);
    doc.setLineWidth(0.4);
    doc.roundedRect(M, y, CW, noticeH, 2, 2, "S");
    let ny = y + padTop;
    doc.setTextColor(...NAVY);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text("About Your Data", M + padX, ny);
    ny += titleLineH;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...CHARCOAL);
    for (const line of bodyLines) { doc.text(line, M + padX, ny); ny += bodyLineH; }
  } else {
    doc.setTextColor(...NAVY);
    doc.setFont("times", "bold");
    doc.setFontSize(12);
    doc.text("Notices", M, y);
    y += 7;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...CHARCOAL);
    const notices = [
      `This document contains the patient's full responses to "${activity.title}". ` +
      `Responses are reproduced exactly as entered. ` +
      `Clinical interpretation remains the sole responsibility of the treating clinician.`,
      ``,
      `This document contains PHI. Store and transmit according to your practice's ` +
      `security policies and applicable regulations.`,
    ];
    for (const notice of notices) {
      const wrapped = doc.splitTextToSize(notice, CW - 2);
      for (const line of wrapped) {
        y = checkPage(y, 5);
        doc.setTextColor(...CHARCOAL);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(7.5);
        doc.text(line, M, y);
        y += 4;
      }
    }
  }

  // Footer on last page
  drawFooter(doc, currentPage, totalPages, variant);

  // Fix page count
  totalPages = currentPage;
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let p = 1; p <= pageCount; p++) {
    doc.setPage(p);
    doc.setFillColor(255, 255, 255);
    doc.rect(PAGE_W / 2 - 15, PAGE_H - 16, 30, 6, "F");
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...CHARCOAL);
    const pg = `${p} / ${totalPages}`;
    const pgW = doc.getTextWidth(pg);
    doc.text(pg, (PAGE_W - pgW) / 2, PAGE_H - 12);
  }

  return doc.output("arraybuffer") as unknown as Uint8Array;
}
