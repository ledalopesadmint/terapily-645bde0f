/**
 * Drag & Drop Result PDF — per-activity document for drag_drop archetype.
 *
 * SERVER-ONLY. Two variants:
 *   - "patient"   → Visual zone/card map, highlights, next steps, disclaimer
 *   - "therapist" → + accuracy table, derived metrics, clinical observations, flags, raw data
 *
 * Three sub-modes: card_sort, ranking_ladder, cycle_builder.
 * Brand rules: same as Scale/Worksheet Result (Navy header, watermark, footer).
 *
 * Prohibited words: improving, worsening, better, worse, progress,
 *   trend analysis, regression, prediction, clinically significant,
 *   HIPAA-certified, court-defensible, legally binding, guaranteed,
 *   diagnosis, treatment plan
 */

import { jsPDF } from "jspdf";
import { supabaseAdmin } from "@/integrations/supabase/client.server";
import { decryptPHIServer } from "@/lib/crypto/encryption.server";
import { logServerError } from "@/lib/logger.server";
import { ICON_PNG_B64, WATERMARK_PNG_B64 } from "./pdf-brand-assets.server";

// ── Brand colors ──
const NAVY = [31, 42, 54] as const;
const CREAM = [244, 239, 230] as const;
const SAGE = [126, 155, 134] as const;
const CHARCOAL = [58, 63, 71] as const;
const WHITE = [255, 255, 255] as const;
const RED = [192, 57, 43] as const;

const M = 18;
const PAGE_W = 210;
const PAGE_H = 297;
const CW = PAGE_W - M * 2;
const FOOTER_ZONE = PAGE_H - 22;

type DragDropResultVariant = "patient" | "therapist";

export interface DragDropResultParams {
  activityResponseId: string;
  workspaceId: string;
  variant: DragDropResultVariant;
  therapistName?: string;
  workspaceName?: string;
  licenseNumber?: string;
  npi?: string;
}

interface CardPlacement {
  cardId: string;
  zoneId?: string;
  slotId?: string;
  rank?: number;
  order?: number;
}

interface ZoneDef {
  id: string;
  label: string;
  color?: string;
  description?: string;
}

interface CardDef {
  id: string;
  text: string;
  label?: string;
}

interface SlotDef {
  id: string;
  label: string;
  position: number;
  placeholder?: string;
}

// ── Shared layout helpers (same as scale-result-pdf) ──

function drawWatermark(doc: jsPDF) {
  const gs = (doc as any).GState;
  if (gs) {
    doc.saveGraphicsState();
    doc.setGState(new gs({ opacity: 0.045 }));
    const size = 120;
    doc.addImage(
      `data:image/png;base64,${WATERMARK_PNG_B64}`,
      "PNG",
      (PAGE_W - size) / 2,
      (PAGE_H - size) / 2,
      size,
      size,
    );
    doc.restoreGraphicsState();
  }
}

function drawHeader(doc: jsPDF): number {
  const barH = 18;
  doc.setFillColor(...NAVY);
  doc.rect(0, 0, PAGE_W, barH, "F");
  const iconSize = 10;
  const iconY = (barH - iconSize) / 2;
  doc.addImage(`data:image/png;base64,${ICON_PNG_B64}`, "PNG", M, iconY, iconSize, iconSize);
  doc.setFont("times", "bold");
  doc.setFontSize(16);
  doc.setTextColor(...CREAM);
  const wmX = M + iconSize + 3;
  const wmY = barH / 2 + 2;
  doc.text("terapily", wmX, wmY);
  const dotX = wmX + doc.getTextWidth("terapily");
  doc.setTextColor(...SAGE);
  doc.text(".", dotX, wmY);
  return barH;
}

function drawFooter(doc: jsPDF, pageNum: number, totalPages: number, variant: DragDropResultVariant) {
  const fy = PAGE_H - 14;
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.3);
  doc.line(M, fy - 2, PAGE_W - M, fy - 2);

  const iconS = 4;
  doc.addImage(`data:image/png;base64,${ICON_PNG_B64}`, "PNG", M, fy - 0.5, iconS, iconS);
  doc.setFont("times", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor(...NAVY);
  const wmX = M + iconS + 1.5;
  doc.text("terapily", wmX, fy + 2);
  doc.setTextColor(...SAGE);
  doc.text(".", wmX + doc.getTextWidth("terapily"), fy + 2);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(6.5);
  doc.setTextColor(...CHARCOAL);
  const yearX = wmX + doc.getTextWidth("terapily.") + 2;
  doc.text(`· ${new Date().getFullYear()}`, yearX, fy + 2);

  doc.setFontSize(7);
  const pg = `${pageNum} / ${totalPages}`;
  const pgW = doc.getTextWidth(pg);
  doc.text(pg, (PAGE_W - pgW) / 2, fy + 2);

  doc.setFontSize(5.5);
  doc.setTextColor(153, 153, 153);
  const disc =
    variant === "patient"
      ? "This document was generated by Terapily. It is not a diagnosis or treatment recommendation."
      : "Platform-generated activity summary. Contains PHI. Store securely per your practice's policies.";
  const discW = doc.getTextWidth(disc);
  doc.text(disc, PAGE_W - M - discW, fy + 6);
}

function formatFullDateTime(iso: string): string {
  return new Date(iso).toLocaleString("en-US", {
    month: "short", day: "numeric", year: "numeric",
    hour: "2-digit", minute: "2-digit", timeZoneName: "short",
  });
}

// ── Main builder ──

export async function buildDragDropResultPDF(params: DragDropResultParams): Promise<Uint8Array> {
  const { activityResponseId, workspaceId, variant } = params;

  // 1. Fetch activity_response
  const { data: resp, error: respErr } = await supabaseAdmin
    .from("activity_responses")
    .select("*")
    .eq("id", activityResponseId)
    .eq("workspace_id", workspaceId)
    .single();

  if (respErr || !resp) {
    throw new Error("Activity response not found.");
  }

  // 2. Fetch patient
  const { data: patient } = await supabaseAdmin
    .from("patients")
    .select("display_name, full_name_encrypted")
    .eq("id", resp.patient_id)
    .eq("workspace_id", workspaceId)
    .maybeSingle();

  let patientLabel = patient?.display_name ?? "Participant";
  let hasPHI = false;
  if (patient?.full_name_encrypted) {
    try {
      const decrypted = await decryptPHIServer(patient.full_name_encrypted);
      if (decrypted) { patientLabel = decrypted; hasPHI = true; }
    } catch (err) { logServerError("drag-drop-result-pdf.decrypt", err); }
  }

  // 3. Fetch activity catalog
  const { data: activity } = await supabaseAdmin
    .from("activity_catalog")
    .select("title, slug, config, archetype")
    .eq("id", resp.activity_id)
    .single();

  if (!activity) throw new Error("Activity not found in catalog.");

  const config = (activity.config ?? {}) as {
    mode?: string;
    instruction?: string;
    cards?: CardDef[];
    zones?: ZoneDef[];
    slots?: SlotDef[];
    topLabel?: string;
    bottomLabel?: string;
    reference_key?: Record<string, string>;
    clinical_reference?: string;
    introduction?: string;
  };

  const mode = config.mode ?? "card_sort";
  const cards = config.cards ?? [];
  const zones = config.zones ?? [];
  const slots = config.slots ?? [];
  const referenceKey = config.reference_key ?? {};

  // 4. Parse response data (stored encrypted in raw_responses_encrypted)
  let responseData: { mode?: string; placements?: CardPlacement[]; duration_seconds?: number } = {};
  if (resp.raw_responses_encrypted) {
    try {
      const decrypted = await decryptPHIServer(resp.raw_responses_encrypted);
      if (decrypted) responseData = JSON.parse(decrypted);
    } catch (err) { logServerError("drag-drop-result-pdf.decrypt-responses", err); }
  }

  const placements: CardPlacement[] = responseData.placements ?? [];
  const durationS = responseData.duration_seconds ?? 0;

  // 5. Fetch delivery_mode
  const { data: pa } = await supabaseAdmin
    .from("patient_activities")
    .select("delivery_mode")
    .eq("id", resp.patient_activity_id)
    .maybeSingle();

  const deliveryMode = pa?.delivery_mode ?? resp.submitted_via ?? "unknown";

  // ── Build PDF ──
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  let totalPages = 1;
  let currentPage = 1;

  function checkPage(y: number, needed = 10): number {
    if (y + needed > FOOTER_ZONE) {
      drawFooter(doc, currentPage, totalPages, variant);
      doc.addPage();
      currentPage++;
      drawWatermark(doc);
      return drawHeader(doc) + 9;
    }
    return y;
  }

  drawWatermark(doc);
  let y = drawHeader(doc);

  // Clinician copy band (therapist only)
  if (variant === "therapist") {
    const bandH = 10;
    doc.setFillColor(253, 232, 232);
    doc.rect(0, y, PAGE_W, bandH, "F");
    doc.setTextColor(...RED);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    const bandLabel = "CLINICIAN COPY \u2014 NOT INTENDED FOR PATIENT DISTRIBUTION";
    const bandW = doc.getTextWidth(bandLabel);
    doc.text(bandLabel, (PAGE_W - bandW) / 2, y + bandH / 2 + 1.5);
    y += bandH;
  }

  y += 10;

  // Title
  doc.setTextColor(...NAVY);
  doc.setFont("times", "bold");
  doc.setFontSize(20);
  doc.text(variant === "patient" ? "Activity Results" : "Clinical Activity Record", M, y);
  y += 5;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...CHARCOAL);
  doc.text(
    variant === "patient"
      ? "Summary of your responses"
      : "Detailed results for your clinical records",
    M, y,
  );
  y += 5;

  // PHI warning (therapist only)
  if (variant === "therapist" && hasPHI) {
    y += 2;
    doc.setFillColor(255, 243, 224);
    doc.roundedRect(M, y, CW, 8, 1.5, 1.5, "F");
    doc.setTextColor(230, 81, 0);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(7);
    doc.text("PHI WARNING:", M + 3, y + 5);
    doc.setFont("helvetica", "normal");
    doc.text("This document contains Protected Health Information. Store securely per your practice's policies.", M + 28, y + 5);
    y += 10;
  } else {
    y += 3;
  }

  // Info box
  const genStr = formatFullDateTime(new Date().toISOString());
  const infoItems: [string, string][] = [
    [variant === "patient" ? "Participant:" : "Patient:", patientLabel],
    ["Activity:", activity.title],
    ["Date:", formatFullDateTime(resp.submitted_at)],
    ["Mode:", deliveryMode.replace("_", " ")],
  ];
  if (variant === "therapist") {
    if (params.therapistName) infoItems.push(["Therapist:", params.therapistName]);
    if (params.workspaceName) infoItems.push(["Practice:", params.workspaceName]);
    if (params.licenseNumber) infoItems.push(["License:", params.licenseNumber]);
    if (params.npi) infoItems.push(["NPI:", params.npi]);
    infoItems.push(["Generated:", genStr]);
  } else {
    infoItems.push(["Generated:", genStr]);
  }

  const infoLineH = 6;
  const infoPadY = 6;
  const infoBoxH = infoPadY * 2 + infoItems.length * infoLineH;
  doc.setFillColor(247, 245, 240);
  doc.roundedRect(M, y, CW, infoBoxH, 2, 2, "F");
  let iy = y + infoPadY + 4;
  for (const [label, val] of infoItems) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...NAVY);
    doc.text(label, M + 4, iy);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...CHARCOAL);
    doc.text(val, M + 30, iy);
    iy += infoLineH;
  }
  y += infoBoxH + 8;

  // ═══ CARD SORT ═══
  if (mode === "card_sort") {
    // Group cards by assigned zone
    const zoneCards: Record<string, CardPlacement[]> = {};
    for (const p of placements) {
      if (p.zoneId) {
        if (!zoneCards[p.zoneId]) zoneCards[p.zoneId] = [];
        zoneCards[p.zoneId].push(p);
      }
    }

    // ── Your Results / Structured Results ──
    y = checkPage(y, 15);
    doc.setFillColor(...SAGE);
    doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
    doc.setTextColor(...WHITE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text(variant === "patient" ? "Your Results" : "Structured Results \u2014 Card Placement", M + 4, y + 6);
    y += 13;

    if (variant === "patient") {
      // Visual zone/card layout
      for (const zone of zones) {
        const zCards = zoneCards[zone.id] ?? [];
        y = checkPage(y, 12 + zCards.length * 10);
        doc.setTextColor(...NAVY);
        doc.setFont("helvetica", "bold");
        doc.setFontSize(9);
        doc.text(`${zone.label}  (${zCards.length} card${zCards.length !== 1 ? "s" : ""})`, M + 2, y);
        y += 5;
        for (const cp of zCards) {
          const card = cards.find((c) => c.id === cp.cardId);
          if (!card) continue;
          y = checkPage(y, 10);
          const boxH = 8;
          doc.setFillColor(252, 251, 248);
          doc.setDrawColor(220, 218, 210);
          doc.setLineWidth(0.3);
          doc.roundedRect(M + 4, y, CW - 8, boxH, 1.5, 1.5, "FD");
          doc.setTextColor(...CHARCOAL);
          doc.setFont("helvetica", "normal");
          doc.setFontSize(8);
          const cardText = `"${card.text}"`;
          const truncText = cardText.length > 80 ? cardText.slice(0, 77) + "..." : cardText;
          doc.text(truncText, M + 8, y + boxH / 2 + 1);
          y += boxH + 1.5;
        }
        y += 3;
      }
    } else {
      // Therapist: full table
      const colX = [M + 2, M + 90, M + 130, M + 160];
      doc.setFont("helvetica", "bold");
      doc.setFontSize(7);
      doc.setTextColor(...NAVY);
      for (const [lbl, x] of [["Card Text", colX[0]], ["Assigned Zone", colX[1]], ["Reference Zone", colX[2]], ["Match", colX[3]]] as const) {
        doc.text(lbl, x, y);
      }
      y += 2;
      doc.setDrawColor(220, 218, 210);
      doc.setLineWidth(0.3);
      doc.line(M, y, PAGE_W - M, y);
      y += 4;

      const zoneMap: Record<string, string> = {};
      for (const z of zones) zoneMap[z.id] = z.label;

      doc.setFont("helvetica", "normal");
      doc.setFontSize(7);
      for (const p of placements) {
        y = checkPage(y, 5);
        const card = cards.find((c) => c.id === p.cardId);
        const cardText = card ? card.text : p.cardId;
        const truncText = cardText.length > 50 ? cardText.slice(0, 47) + "..." : cardText;
        doc.setTextColor(...CHARCOAL);
        doc.text(truncText, colX[0], y);
        doc.text((zoneMap[p.zoneId ?? ""] ?? "—").slice(0, 18), colX[1], y);
        const refZone = referenceKey[p.cardId] ?? "—";
        doc.text((zoneMap[refZone] ?? refZone).slice(0, 18), colX[2], y);
        const isMatch = p.zoneId === refZone;
        const hasRef = !!referenceKey[p.cardId];
        const matchColor = hasRef ? (isMatch ? SAGE : RED) : CHARCOAL;
        doc.setTextColor(matchColor[0], matchColor[1], matchColor[2]);
        doc.text(hasRef ? (isMatch ? "Yes" : "No") : "N/A", colX[3], y);
        y += 4.5;
      }
      y += 6;

      // Derived Metrics
      y = checkPage(y, 40);
      doc.setFillColor(...SAGE);
      doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
      doc.setTextColor(...WHITE);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.text("Derived Metrics", M + 4, y + 6);
      y += 13;

      const hasRefKey = Object.keys(referenceKey).length > 0;
      const correct = hasRefKey ? placements.filter((p) => p.zoneId === referenceKey[p.cardId]).length : 0;
      const accuracy = hasRefKey ? Math.round((correct / placements.length) * 100) : null;

      const maxZoneCount = Math.max(...Object.values(zoneCards).map((v) => v.length), 0);
      const concentration = placements.length > 0 ? Math.round((maxZoneCount / placements.length) * 100) : 0;
      const emptyZones = zones.filter((z) => !zoneCards[z.id] || zoneCards[z.id].length === 0).length;
      const blindSpots = Math.round((emptyZones / zones.length) * 100);

      const metrics: [string, string][] = [];
      if (accuracy !== null) metrics.push(["Accuracy:", `${accuracy}% (${correct}/${placements.length} cards correctly placed)`]);
      metrics.push(["Concentration Index:", `${concentration}% (most cards in one zone: ${maxZoneCount})`]);
      metrics.push(["Blind Spots:", `${blindSpots}% (${emptyZones}/${zones.length} zones empty)`]);
      metrics.push(["Duration:", `${Math.floor(durationS / 60)}m ${durationS % 60}s`]);

      for (const [lbl, val] of metrics) {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(8);
        doc.setTextColor(...NAVY);
        doc.text(lbl, M + 4, y);
        doc.setFont("helvetica", "normal");
        doc.setTextColor(...CHARCOAL);
        doc.text(val, M + 42, y);
        y += 5.5;
      }
      y += 6;

      // Clinical Observations
      y = checkPage(y, 30);
      doc.setFillColor(...SAGE);
      doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
      doc.setTextColor(...WHITE);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.text("Clinical Observations", M + 4, y + 6);
      y += 13;

      const observations: string[] = [];

      // Misclassified cards
      if (hasRefKey) {
        const wrong = placements.filter((p) => referenceKey[p.cardId] && p.zoneId !== referenceKey[p.cardId]);
        if (wrong.length > 0) {
          for (const w of wrong.slice(0, 3)) {
            const card = cards.find((c) => c.id === w.cardId);
            const assigned = zoneMap[w.zoneId ?? ""] ?? w.zoneId;
            const expected = zoneMap[referenceKey[w.cardId]] ?? referenceKey[w.cardId];
            observations.push(
              `Card "${card?.text?.slice(0, 40) ?? w.cardId}" was placed in ${assigned} but references ${expected}.`,
            );
          }
        }
      }

      if (blindSpots === 0) {
        observations.push("Zero blind spots: patient engaged with all categories.");
      } else if (blindSpots > 30) {
        const emptyNames = zones.filter((z) => !zoneCards[z.id]).map((z) => z.label).join(", ");
        observations.push(`Empty zones detected: ${emptyNames}. Consider exploring these patterns.`);
      }

      if (observations.length === 0) {
        observations.push("No notable patterns detected in this application.");
      }

      for (const obs of observations) {
        const lines = doc.splitTextToSize(obs, CW - 12);
        const boxH = Math.max(8, lines.length * 4 + 4);
        y = checkPage(y, boxH + 3);
        doc.setFillColor(252, 251, 248);
        doc.setDrawColor(220, 218, 210);
        doc.setLineWidth(0.3);
        doc.roundedRect(M + 2, y, CW - 4, boxH, 1.5, 1.5, "FD");
        doc.setTextColor(...CHARCOAL);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(7.5);
        let ty = y + 3.5;
        for (const line of lines) {
          doc.text(line, M + 6, ty);
          ty += 4;
        }
        y += boxH + 3;
      }
      y += 4;

      // Clinical Flags
      if (hasRefKey) {
        const wrongCards = placements.filter((p) => referenceKey[p.cardId] && p.zoneId !== referenceKey[p.cardId]);
        if (wrongCards.length > 0) {
          y = checkPage(y, 20);
          doc.setFillColor(...SAGE);
          doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
          doc.setTextColor(...WHITE);
          doc.setFont("helvetica", "bold");
          doc.setFontSize(9);
          doc.text("Clinical Flags", M + 4, y + 6);
          y += 13;

          const flagText = `${wrongCards.length} card${wrongCards.length > 1 ? "s" : ""} misclassified. Consider targeted psychoeducation on the confused categories.`;
          const flagLines = doc.splitTextToSize(flagText, CW - 16);
          const flagH = Math.max(7, flagLines.length * 3.5 + 4);
          doc.setFillColor(255, 243, 224);
          doc.roundedRect(M + 2, y, CW - 4, flagH, 1, 1, "F");
          doc.setTextColor(230, 81, 0);
          doc.setFont("helvetica", "bold");
          doc.setFontSize(6.5);
          let fy = y + 3.5;
          for (const line of flagLines) {
            doc.text(line, M + 5, fy);
            fy += 3.5;
          }
          y += flagH + 6;
        }
      }
    }
  }

  // ═══ RANKING LADDER ═══
  if (mode === "ranking_ladder") {
    y = checkPage(y, 15);
    doc.setFillColor(...SAGE);
    doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
    doc.setTextColor(...WHITE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text(variant === "patient" ? "Your Hierarchy" : "Exposure Hierarchy \u2014 Ranking", M + 4, y + 6);
    y += 13;

    const sorted = [...placements].sort((a, b) => (a.rank ?? 0) - (b.rank ?? 0));

    for (const p of sorted) {
      y = checkPage(y, 10);
      const card = cards.find((c) => c.id === p.cardId);
      const boxH = 8;
      doc.setFillColor(252, 251, 248);
      doc.setDrawColor(220, 218, 210);
      doc.setLineWidth(0.3);
      doc.roundedRect(M + 4, y, CW - 8, boxH, 1.5, 1.5, "FD");
      doc.setTextColor(...NAVY);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);
      doc.text(`#${p.rank ?? "?"}`, M + 8, y + boxH / 2 + 1);
      doc.setTextColor(...CHARCOAL);
      doc.setFont("helvetica", "normal");
      const cardText = card?.text ?? p.cardId;
      const truncText = cardText.length > 60 ? cardText.slice(0, 57) + "..." : cardText;
      doc.text(truncText, M + 20, y + boxH / 2 + 1);
      y += boxH + 1.5;
    }

    if (variant === "therapist") {
      y += 6;
      y = checkPage(y, 20);
      doc.setFillColor(...SAGE);
      doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
      doc.setTextColor(...WHITE);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.text("Derived Metrics", M + 4, y + 6);
      y += 13;

      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);
      doc.setTextColor(...NAVY);
      doc.text("Items ranked:", M + 4, y);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(...CHARCOAL);
      doc.text(`${sorted.length}`, M + 42, y);
      y += 5.5;
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...NAVY);
      doc.text("Duration:", M + 4, y);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(...CHARCOAL);
      doc.text(`${Math.floor(durationS / 60)}m ${durationS % 60}s`, M + 42, y);
      y += 8;
    }
  }

  // ═══ CYCLE BUILDER ═══
  if (mode === "cycle_builder") {
    y = checkPage(y, 15);
    doc.setFillColor(...SAGE);
    doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
    doc.setTextColor(...WHITE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text(variant === "patient" ? "Your Cycle" : "Cycle Builder \u2014 Slot Mapping", M + 4, y + 6);
    y += 13;

    const sortedSlots = [...slots].sort((a, b) => a.position - b.position);
    for (const slot of sortedSlots) {
      const placed = placements.find((p) => p.slotId === slot.id);
      const card = placed ? cards.find((c) => c.id === placed.cardId) : null;
      y = checkPage(y, 14);

      // Slot label
      doc.setTextColor(...NAVY);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);
      doc.text(`${slot.label}:`, M + 2, y);
      y += 4;

      // Card in slot
      const boxH = 8;
      doc.setFillColor(252, 251, 248);
      doc.setDrawColor(220, 218, 210);
      doc.setLineWidth(0.3);
      doc.roundedRect(M + 4, y, CW - 8, boxH, 1.5, 1.5, "FD");
      doc.setTextColor(...CHARCOAL);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.text(card ? `"${card.text}"` : "(empty)", M + 8, y + boxH / 2 + 1);
      y += boxH + 4;
    }

    if (variant === "therapist") {
      y += 4;
      y = checkPage(y, 20);
      doc.setFillColor(...SAGE);
      doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
      doc.setTextColor(...WHITE);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.text("Derived Metrics", M + 4, y + 6);
      y += 13;

      const filled = slots.filter((s) => placements.some((p) => p.slotId === s.id)).length;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);
      doc.setTextColor(...NAVY);
      doc.text("Completeness:", M + 4, y);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(...CHARCOAL);
      doc.text(`${filled}/${slots.length} slots filled (${Math.round((filled / slots.length) * 100)}%)`, M + 42, y);
      y += 5.5;
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...NAVY);
      doc.text("Duration:", M + 4, y);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(...CHARCOAL);
      doc.text(`${Math.floor(durationS / 60)}m ${durationS % 60}s`, M + 42, y);
      y += 8;
    }
  }

  // ═══ Highlights (patient only) ═══
  if (variant === "patient") {
    y = checkPage(y, 30);
    doc.setFillColor(...SAGE);
    doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
    doc.setTextColor(...WHITE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text("Highlights", M + 4, y + 6);
    y += 13;

    const highlights: string[] = [];
    if (mode === "card_sort") {
      highlights.push(`You placed ${placements.length} cards across ${zones.length} categories.`);
      const hasRefKey = Object.keys(referenceKey).length > 0;
      if (hasRefKey) {
        const correct = placements.filter((p) => p.zoneId === referenceKey[p.cardId]).length;
        highlights.push(`You recognized ${correct} of ${placements.length} patterns correctly.`);
      }
    } else if (mode === "ranking_ladder") {
      highlights.push(`You ranked ${placements.length} items in your personal hierarchy.`);
    } else if (mode === "cycle_builder") {
      const filled = slots.filter((s) => placements.some((p) => p.slotId === s.id)).length;
      highlights.push(`You completed ${filled} of ${slots.length} cycle slots.`);
    }
    highlights.push(`Time to complete: ${Math.floor(durationS / 60)} minutes ${durationS % 60} seconds.`);
    highlights.push("Great work engaging with this activity!");

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...CHARCOAL);
    for (const h of highlights) {
      doc.text(`\u2022 ${h}`, M + 4, y);
      y += 5;
    }
    y += 4;

    // Next Steps
    y = checkPage(y, 25);
    doc.setFillColor(...SAGE);
    doc.roundedRect(M, y, CW, 9, 1.5, 1.5, "F");
    doc.setTextColor(...WHITE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text("Next Steps", M + 4, y + 6);
    y += 13;

    const nextSteps = [
      "Discuss these results with your therapist in your next session.",
      "You may redo this activity later to track changes.",
      "Remember: engaging with these exercises is a meaningful step.",
    ];
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...CHARCOAL);
    for (const ns of nextSteps) {
      doc.text(`\u2022 ${ns}`, M + 4, y);
      y += 5;
    }
    y += 6;
  }

  // ═══ Notice ═══
  y = checkPage(y, 40);
  if (variant === "patient") {
    const padX = 6;
    const padTop = 7;
    const padBottom = 7;
    const titleLineH = 6;
    const bodyLineH = 4;

    const bodyLines = [
      "Your responses are stored securely and shared only with your therapist.",
      "This document summarizes your activity \u2014 it is not a clinical evaluation.",
      "Your therapist may use these results as part of your treatment planning.",
      "You consented to this activity before starting. Your consent record is stored securely.",
    ];
    const noticeH = padTop + titleLineH + bodyLines.length * bodyLineH + padBottom;
    doc.setFillColor(255, 248, 225);
    doc.roundedRect(M, y, CW, noticeH, 2, 2, "F");
    doc.setDrawColor(240, 208, 96);
    doc.setLineWidth(0.4);
    doc.roundedRect(M, y, CW, noticeH, 2, 2, "S");
    let ny = y + padTop;
    doc.setTextColor(...NAVY);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text("About Your Data", M + padX, ny);
    ny += titleLineH;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...CHARCOAL);
    for (const line of bodyLines) { doc.text(line, M + padX, ny); ny += bodyLineH; }

    // Reference
    y += noticeH + 6;
    if (config.clinical_reference) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(6);
      doc.setTextColor(153, 153, 153);
      const refLines = doc.splitTextToSize(`Reference: ${config.clinical_reference}`, CW);
      for (const rl of refLines) {
        doc.text(rl, M, y);
        y += 3.5;
      }
    }
  } else {
    doc.setTextColor(...NAVY);
    doc.setFont("times", "bold");
    doc.setFontSize(12);
    doc.text("Notices", M, y);
    y += 7;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...CHARCOAL);
    const notices = [
      "Responses are reproduced exactly as submitted by the participant. Terapily does not alter or interpret responses.",
      "Clinical interpretation and treatment decisions remain the sole responsibility of the licensed clinician.",
      "If this document contains PHI, store and dispose of it in accordance with your practice's HIPAA policies.",
    ];
    if (config.clinical_reference) {
      notices.push(`Activity based on: ${config.clinical_reference}`);
    }
    for (const notice of notices) {
      const wrapped = doc.splitTextToSize(notice, CW - 2);
      for (const line of wrapped) {
        y = checkPage(y, 5);
        doc.text(line, M, y);
        y += 4;
      }
      y += 1;
    }
  }

  // Footer on last page
  drawFooter(doc, currentPage, totalPages, variant);

  // Fix page count
  totalPages = currentPage;
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let p = 1; p <= pageCount; p++) {
    doc.setPage(p);
    doc.setFillColor(255, 255, 255);
    doc.rect(PAGE_W / 2 - 15, PAGE_H - 16, 30, 6, "F");
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...CHARCOAL);
    const pg = `${p} / ${totalPages}`;
    const pgW = doc.getTextWidth(pg);
    doc.text(pg, (PAGE_W - pgW) / 2, PAGE_H - 12);
  }

  return doc.output("arraybuffer") as unknown as Uint8Array;
}
